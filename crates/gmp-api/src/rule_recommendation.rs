/// Historical violation record (input for analysis)
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ViolationRecord {
    pub violation_id: String,
    pub description: String,
    pub category: String,
    pub severity: Severity,
    pub location: String,
    pub equipment_id: Option<String>,
    pub product_id: Option<String>,
    pub occurred_at: DateTime<Utc>,
    pub related_rule_ids: Vec<String>,
}

impl ViolationRecord {
    pub fn cluster_type(&self) -> ClusterType {
        let desc_lower = self.description.to_lowercase();
        let cat_lower = self.category.to_lowercase();

        if desc_lower.contains("equipment")
            || desc_lower.contains("device")
            || desc_lower.contains("instrument")
            || cat_lower.contains("equipment")
        {
            ClusterType::Equipment
        } else if desc_lower.contains("temperature") || cat_lower.contains("temperature") {
            ClusterType::Temperature
        } else if desc_lower.contains("human")
            || desc_lower.contains("operator")
            || desc_lower.contains("staff")
            || cat_lower.contains("human")
        {
            ClusterType::Human
        } else if desc_lower.contains("process")
            || desc_lower.contains("procedure")
            || cat_lower.contains("process")
        {
            ClusterType::Process
        } else if desc_lower.contains("material")
            || desc_lower.contains("raw material")
            || cat_lower.contains("material")
        {
            ClusterType::Material
        } else if desc_lower.contains("environment")
            || desc_lower.contains("cleanroom")
            || cat_lower.contains("environmental")
        {
            ClusterType::Environmental
        } else {
            ClusterType::Unknown
        }
    }
}

