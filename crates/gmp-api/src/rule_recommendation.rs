/// Violation severity levels
#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq, Hash)]
pub enum Severity {
    Critical,
    High,
    Medium,
    Low,
    Info,
}

impl Severity {
    pub fn weight(&self) -> f64 {
        match self {
            Self::Critical => 5.0,
            Self::High => 4.0,
            Self::Medium => 3.0,
            Self::Low => 2.0,
            Self::Info => 1.0,
        }
    }

    pub fn as_str(&self) -> &'static str {
        match self {
            Self::Critical => "critical",
            Self::High => "high",
            Self::Medium => "medium",
            Self::Low => "low",
            Self::Info => "info",
        }
    }
}

/// Violation pattern clustered from historical data
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ViolationPattern {
    pub pattern_id: String,
    pub cluster_type: ClusterType,
    pub description: String,
    pub frequency: u32,
    pub severity_distribution: HashMap<Severity, u32>,
    pub related_rules: Vec<String>,
    pub gap_score: f64,
}

#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq, Hash)]
pub enum ClusterType {
    Equipment,
    Human,
    Process,
    Material,
    Environmental,
    Temperature,
    Quality,
    Safety,
    Unknown,
}

impl ClusterType {
    pub fn as_str(&self) -> &'static str {
        match self {
            Self::Equipment => "equipment",
            Self::Human => "human",
            Self::Process => "process",
            Self::Material => "material",
            Self::Environmental => "environmental",
            Self::Temperature => "temperature",
            Self::Quality => "quality",
            Self::Safety => "safety",
            Self::Unknown => "unknown",
        }
    }
}

/// Weighted severity score for a pattern
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct WeightedSeverity {
    pub critical: u32,
    pub high: u32,
    pub medium: u32,
    pub low: u32,
    pub info: u32,
}

impl WeightedSeverity {
    pub fn total_weighted_score(&self) -> f64 {
        (self.critical as f64 * Severity::Critical.weight())
            + (self.high as f64 * Severity::High.weight())
            + (self.medium as f64 * Severity::Medium.weight())
            + (self.low as f64 * Severity::Low.weight())
            + (self.info as f64 * Severity::Info.weight())
    }
}

/// Recommendation status workflow
#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq)]
pub enum RecommendationStatus {
    Draft,
    UnderReview,
    Approved,
    Rejected,
    Implemented,
}

impl RecommendationStatus {
    pub fn as_str(&self) -> &'static str {
        match self {
            Self::Draft => "draft",
            Self::UnderReview => "under_review",
            Self::Approved => "approved",
            Self::Rejected => "rejected",
            Self::Implemented => "implemented",
        }
    }
}

/// Review decision
#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq)]
pub enum Decision {
    Approve,
    Reject,
}

/// Review audit record
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ReviewRecord {
    pub reviewer: String,
    pub decision: Decision,
    pub comment: String,
    pub reviewed_at: DateTime<Utc>,
}

/// Rule recommendation generated by the engine
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RuleRecommendation {
    pub recommendation_id: String,
    pub title: String,
    pub scope: String,
    pub requirement: String,
    pub rationale: String,
    pub supporting_patterns: Vec<String>,
    pub supporting_violations: Vec<String>,
    pub confidence: f64,
    pub proposed_at: DateTime<Utc>,
    pub status: RecommendationStatus,
    pub review_history: Vec<ReviewRecord>,
}

impl RuleRecommendation {
    pub fn new(
        title: String,
        scope: String,
        requirement: String,
        rationale: String,
        supporting_patterns: Vec<String>,
        supporting_violations: Vec<String>,
        confidence: f64,
    ) -> Self {
        Self {
            recommendation_id: Uuid::new_v4().to_string(),
            title,
            scope,
            requirement,
            rationale,
            supporting_patterns,
            supporting_violations,
            confidence: confidence.clamp(0.0, 1.0),
            proposed_at: Utc::now(),
            status: RecommendationStatus::Draft,
            review_history: Vec::new(),
        }
    }

    pub fn submit_for_review(&mut self) {
        if self.status == RecommendationStatus::Draft {
            self.status = RecommendationStatus::UnderReview;
        }
    }

    pub fn review(&mut self, reviewer: String, decision: Decision, comment: String) {
        self.status = match decision {
            Decision::Approve => RecommendationStatus::Approved,
            Decision::Reject => RecommendationStatus::Rejected,
        };
        self.review_history.push(ReviewRecord {
            reviewer,
            decision,
            comment,
            reviewed_at: Utc::now(),
        });
    }
}

