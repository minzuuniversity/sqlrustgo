// ─── Event Type Enum ─────────────────────────────────────────────────────────

/// Event type tags for handler filtering
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum GmpEventType {
    Device,
    Audit,
    Workflow,
    Document,
    Agent,
    System,
    All,
}

impl GmpEventType {
    /// Infer event type from a GmpEvent
    pub fn from_event(event: &GmpEvent) -> Self {
        match event {
            GmpEvent::Device(_) => GmpEventType::Device,
            GmpEvent::Audit(_) => GmpEventType::Audit,
            GmpEvent::Workflow(_) => GmpEventType::Workflow,
            GmpEvent::Document(_) => GmpEventType::Document,
            GmpEvent::Agent(_) => GmpEventType::Agent,
            GmpEvent::System(_) => GmpEventType::System,
        }
    }
}

// ─── Unified Event Wrapper ───────────────────────────────────────────────────

/// Unified event enum — all GMP platform events
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type", content = "data")]
pub enum GmpEvent {
    Device(DeviceEvent),
    Audit(AuditEvent),
    Workflow(WorkflowEvent),
    Document(DocumentEvent),
    Agent(AgentEvent),
    System(SystemEvent),
}

impl GmpEvent {
    /// Extract trace_id from any event for correlation
    pub fn trace_id(&self) -> &str {
        match self {
            GmpEvent::Device(e) => &e.trace_id,
            GmpEvent::Audit(e) => &e.trace_id,
            GmpEvent::Workflow(e) => &e.trace_id,
            GmpEvent::Document(e) => &e.trace_id,
            GmpEvent::Agent(e) => &e.trace_id,
            GmpEvent::System(_) => "system",
        }
    }

    /// Get the event type tag as string
    pub fn type_tag(&self) -> &'static str {
        match self {
            GmpEvent::Device(_) => "device",
            GmpEvent::Audit(_) => "audit",
            GmpEvent::Workflow(_) => "workflow",
            GmpEvent::Document(_) => "document",
            GmpEvent::Agent(_) => "agent",
            GmpEvent::System(_) => "system",
        }
    }
}
