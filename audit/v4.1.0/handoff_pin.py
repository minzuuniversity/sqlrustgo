#!/usr/bin/env python3
"""Pin the handoff startup prompt onto the kanban ISSUE as a marked *comment*.

Note on wording: Gitea has no API for literally pinning a comment, so "pin" here means
"a comment carrying the HANDOFF-PIN marker that this tool creates/updates idempotently".

Why a comment and not the ISSUE body: the body of #5592 is regenerated by
`gen_kanban_issue.py --post`, and two development lines render it. Measured on
2026-11-06: the copy of that generator on develop/v4.1.0 and on
omp-macmini/lb1-arm-count-fix is 236 lines with **zero** appendix support,
while this line's copy is 283 lines and injects 附录 A. So every re-render from
the other lines erases the entry point by construction (not by malice).
Comments are not touched by a body re-render, so the entry point goes here.

    python3 audit/v4.1.0/handoff_pin.py                  # print comment body only
    python3 audit/v4.1.0/handoff_pin.py --post 5592      # create or update the pin

Verb note (measured on Gitea 28.2.0 at 192.168.0.252:3000, 2026-11-06): editing a comment is
`PATCH /repos/{o}/{r}/issues/comments/{id}`; PUT on the same route returns 405. A PUT-based
"update" therefore silently never happens — it is reported as POST-FAIL, not as success.

Hash-base note: the `src_sha256` in the pin marker is the sha256 of the **stripped** source text,
the same base `board_appendix_check.py` uses. It used to be the hash of the raw file bytes, which
made two same-named fields measure different things (handoff section 10, item 24).
    python3 audit/v4.1.0/handoff_pin.py --selftest       # reverse mutation self-test
    python3 audit/v4.1.0/handoff_pin.py --probe-verb     # 现读 Gitea 评论写动词（只碰自建探针，安全）

Honesty rules baked in:
  * if §0.5 cannot be located, or is suspiciously short, exit 2 (INCOMPLETE) —
    "can't verify" is not "published".
  * more than one existing pin -> refuse to guess, exit 2.
  * PAT comes from the git credential helper at call time; never printed,
    stored, or passed on the command line.
"""
import hashlib
import json
import pathlib
import re
import subprocess
import sys
import urllib.error
import urllib.request

NL = "\n"
REPO = pathlib.Path(__file__).resolve().parents[2]
SRC = REPO / "docs/knowledge-loop/handoffs/HANDOFF_2026-11-05_4.1.0_OMP_ONBOARDING.md"
BASE = "http://192.168.0.252:3000/api/v1"
REPO_API = "/repos/openclaw/sqlrustgo"
MARK = "HANDOFF-PIN"
HEADING_RE = re.compile(r"^##\s+0\.5\s+启动提示词")
MIN_SECTION_CHARS = 800


def token() -> str:
    p = subprocess.run(["git", "credential", "fill"],
                       input=b"url=http://192.168.0.252:3000" + NL.encode() + NL.encode(),
                       capture_output=True)
    for line in p.stdout.decode().splitlines():
        if line.startswith("password="):
            return line.split("=", 1)[1]
    raise SystemExit("no credential for http://192.168.0.252:3000")


def sh(*args: str) -> str:
    return subprocess.run(args, cwd=str(REPO), capture_output=True, text=True).stdout.strip()


def api(method: str, path: str, payload=None):
    data = json.dumps(payload).encode() if payload is not None else None
    headers = {"Authorization": "token " + token(), "Accept": "application/json"}
    if data is not None:
        headers["Content-Type"] = "application/json"
    req = urllib.request.Request(BASE + path, data=data, method=method, headers=headers)
    with urllib.request.urlopen(req, timeout=40) as resp:
        raw = resp.read().decode()
        return json.loads(raw) if raw.strip() else {}   # DELETE 返回 204 空体


def extract_section(text: str) -> str:
    lines = text.splitlines()
    start = next((i for i, l in enumerate(lines) if HEADING_RE.match(l)), None)
    if start is None:
        raise SystemExit("SECTION-MISSING: 找不到 “## 0.5 启动提示词” 这一节（交接正文被改名/删节 ⇒ 不许发布）")
    end = next((i for i in range(start + 1, len(lines)) if lines[i].startswith("## ")), len(lines))
    sec = NL.join(lines[start:end]).strip()
    if len(sec) < MIN_SECTION_CHARS:
        raise SystemExit(f"SECTION-TOO-SHORT: 只取到 {len(sec)} 字符（阈值 {MIN_SECTION_CHARS}）")
    if "接手 sqlrustgo" not in sec or "```" not in sec:
        raise SystemExit("SECTION-INCOMPLETE: §0.5 里没有可直接粘贴的 fenced 提示词块")
    return sec


def build_comment() -> str:
    if not SRC.is_file():
        raise SystemExit("SRC-MISSING: " + str(SRC))
    raw = SRC.read_bytes()
    text = raw.decode("utf-8")
    sec = extract_section(text)
    # 哈希基与 board_appendix_check.py 对齐：按 **strip 后正文** 哈希。
    # 之前按原始字节哈希，两个工具字段同名不同基（pin 28814da4… vs 核对器 07c5ac06…），
    # 接手者拿它们互相比对必然误判 ⇒ 见交接 §10 第 24 条。
    body_bytes = text.strip().encode("utf-8")
    src_sha = hashlib.sha256(body_bytes).hexdigest()
    branch, head = sh("git", "rev-parse", "--abbrev-ref", "HEAD"), sh("git", "rev-parse", "HEAD")
    if not branch or not head or branch == "HEAD":
        raise SystemExit("COORD-INCOMPLETE: 读不到分支/HEAD（branch=%r head=%r）" % (branch, head[:10]))
    board = sh("git", "ls-remote", "gitea252",
               "refs/heads/mcode-macmini/governance-kanban-expert-ladder",
               "refs/heads/omp-macmini/lb1-arm-count-fix")
    lines = [f"<!-- {MARK}:src={SRC.name} src_sha256={src_sha[:12]} -->"]
    lines += [
        "## 看板入口（HANDOFF-PIN 固定评论；Gitea 无 API 置顶，按标记检索）",
        "",
        "看板 #5592 的**正文**由 `gen_kanban_issue.py --post 5592` 整段重写，而两条开发线的",
        "生成器不是同一份：develop/v4.1.0 与 omp-macmini/lb1-arm-count-fix 上那份 236 行、",
        "**不含附录注入**；本线这份 283 行、含 `--appendix`。所以只要对方刷新正文，附录 A 就没了——",
        "这是结构性原因，已实测（见交接正文 §2.5）。启动提示词因此放在评论里（评论不受正文重写影响；不是字面「置顶」，Gitea 没有那个 API）。",
        "",
        "**Owner 只要把下面这段贴给接手者，即可交接。** 接手者读完必须去读全文（#5599 正文 = 同一份 SSOT）。",
        "",
        sec,
        "",
        "### 发布元数据（机器生成，勿手改）",
        f"- 源文件（SSOT）：`docs/knowledge-loop/handoffs/{SRC.name}`" f"｜文件 {len(raw)} 字节" f"｜正文 sha256（strip 后，与 `board_appendix_check.py` 同一哈希基）`{src_sha}`",
        f"- 分支 `{branch}` HEAD `{head[:10]}`（已推 gitea252）",
        "- 远端分支 tip 现读（不写死）：",
    ]
    for l in board.splitlines():
        lines.append(f"  - {l}")
    lines += [
        "- 三处一致性机器核对：`/usr/bin/python3 audit/v4.1.0/board_appendix_check.py`"
        "（0 一致 / 1 看板缺附录 / 2 没能核对）；交接正文发布：`audit/v4.1.0/handoff_publish.py --post 5599`。",
    ]
    return NL.join(lines) + NL


def find_pins(issue_no: str):
    out, page = [], 1
    while True:
        rows = api("GET", f"{REPO_API}/issues/{issue_no}/comments?page={page}&limit=50")
        if not rows:
            return out
        out += [r for r in rows if MARK in (r.get("body") or "")]
        if len(rows) < 50:
            return out
        page += 1


def api_status(method: str, path: str, payload=None) -> int:
    """Return the *real* HTTP status (204 and 200 are different facts)."""
    data = json.dumps(payload).encode() if payload is not None else None
    headers = {"Authorization": "token " + token(), "Accept": "application/json"}
    if data is not None:
        headers["Content-Type"] = "application/json"
    req = urllib.request.Request(BASE + path, data=data, method=method, headers=headers)
    try:
        with urllib.request.urlopen(req, timeout=40) as resp:
            resp.read()
            return resp.status
    except urllib.error.HTTPError as e:
        return e.code


def probe_verb() -> int:
    """Re-measure which write verbs this Gitea supports for issue comments.

    Safe by construction: the probe only touches a throwaway comment it creates
    itself (marker HANDOFF-PIN-PROBE), never the published pin — probing a real
    object is what clobbered the pin once (handoff §10 第 23 条).
    Exit 0 only while PUT=405 / PATCH=200 / DELETE=204 hold; if the server
    changes, this goes red instead of letting the tool's assumption rot.
    """
    try:
        created = api("POST", f"{REPO_API}/issues/5592/comments",
                      {"body": f"<!-- {MARK}-PROBE --> verb probe, safe to delete"})
        cid = created["id"]
        put = api_status("PUT", f"{REPO_API}/issues/comments/{cid}", {"body": "put-probe"})
        patch = api_status("PATCH", f"{REPO_API}/issues/comments/{cid}", {"body": "patch-probe"})
        dele = api_status("DELETE", f"{REPO_API}/issues/comments/{cid}")
    except urllib.error.HTTPError as e:
        print("PROBE-INCOMPLETE: http=%s" % e.code, file=sys.stderr)
        return 2
    except (urllib.error.URLError, TimeoutError) as e:
        print("INCOMPLETE: 探不出去 %r" % (e,), file=sys.stderr)
        return 2
    print(json.dumps({"kind": "handoff_pin_verb_probe", "comment_id": cid,
                      "PUT": put, "PATCH": patch, "DELETE": dele,
                      "expected": {"PUT": 405, "PATCH": 200, "DELETE": 204}}, ensure_ascii=False))
    if (put, patch, dele) == (405, 200, 204):
        return 0
    print("NOT-OK: 这台 Gitea 的写动词与工具假设不一致（见交接 §8），先判工具是否要改", file=sys.stderr)
    return 1


def main(argv) -> int:
    post, selftest = None, False
    for i, a in enumerate(argv):
        if a == "--post":
            if i + 1 >= len(argv):
                print("用法: --post <issue_no>", file=sys.stderr)
                return 2
            post = argv[i + 1]
        elif a == "--selftest":
            selftest = True
        elif a == "--probe-verb":
            return probe_verb()
    if selftest:
        good = build_comment()
        assert MARK in good and "接手 sqlrustgo" in good, "A1: 正常源文件必须产出可用评论"
        # 反向变异 M1：删掉 §0.5 标题 -> 必须失败（判据不哑火）
        tmp = pathlib.Path("/tmp/hpin_m1.md")
        tmp.write_text(SRC.read_text(encoding="utf-8").replace("## 0.5 启动提示词", "## 0.5 无关标题"),
                       encoding="utf-8")
        saved = SRC.read_bytes()
        try:
            SRC.write_bytes(tmp.read_bytes())
            try:
                build_comment()
                print("MUTATION-FAIL M1: 缺 §0.5 仍然产出（判据哑火）", file=sys.stderr)
                return 1
            except SystemExit as e:
                assert "SECTION-MISSING" in str(e), f"MUTATION-FAIL M1: 报错了但不是预期判据: {e}"
        finally:
            SRC.write_bytes(saved)
        # 反向变异 M2：§0.5 只剩标题 -> 必须失败
        tmp2 = pathlib.Path("/tmp/hpin_m2.md")
        body = SRC.read_text(encoding="utf-8").splitlines()
        s = next(i for i, l in enumerate(body) if HEADING_RE.match(l))
        e = next(i for i in range(s + 1, len(body)) if body[i].startswith("## "))
        tmp2.write_text(NL.join(body[:s] + [body[s], body[e - 1] if False else "占位"] + body[e:]), encoding="utf-8")
        try:
            SRC.write_bytes(tmp2.read_bytes())
            try:
                build_comment()
                print("MUTATION-FAIL M2: 残缺 §0.5 仍然产出", file=sys.stderr)
                return 1
            except SystemExit as exc:
                assert "SECTION-TOO-SHORT" in str(exc) or "SECTION-INCOMPLETE" in str(exc), \
                    f"MUTATION-FAIL M2: 判据不符: {exc}"
        finally:
            SRC.write_bytes(saved)
        # 反向变异 M3：marker 的哈希基必须是 **strip 后正文**（与 board_appendix_check 同基），
        # 且必须能与「原始字节」基区分开——否则这条判据永远绿着（第 2.5 条反向变异要求）。
        pad = SRC.read_bytes() + b"\n\n   \n"
        base_strip = hashlib.sha256(pad.decode("utf-8").strip().encode("utf-8")).hexdigest()
        base_raw = hashlib.sha256(pad).hexdigest()
        try:
            SRC.write_bytes(pad)
            marker_line = build_comment().splitlines()[0]
        finally:
            SRC.write_bytes(saved)
        if base_strip == base_raw:
            print("MUTATION-FAIL M3: 填充后两种哈希基相同 ⇒ 该臂无法判别", file=sys.stderr)
            return 1
        if base_strip[:12] not in marker_line or base_raw[:12] in marker_line:
            print("MUTATION-FAIL M3: marker 哈希基不是 strip 后正文: %s" % marker_line, file=sys.stderr)
            return 1
        print(json.dumps({"kind": "handoff_pin_selftest", "arms": 3, "discriminating": 3,
                          "hash_base": "strip-then-utf8", "m3_marker": marker_line,
                          "chars_good": len(good)}, ensure_ascii=False))
        return 0

    body = build_comment()
    if post is None:
        sys.stdout.write(body)
        return 0
    pins = find_pins(post)
    try:
        if len(pins) == 0:
            got = api("POST", f"{REPO_API}/issues/{post}/comments", {"body": body})
            mode = "create"
        elif len(pins) == 1:
            got = api("PATCH", f"{REPO_API}/issues/comments/{pins[0]['id']}", {"body": body})
            mode = "update"
        else:
            print(f"INCOMPLETE: 已存在 {len(pins)} 条 pin 评论（id={[p['id'] for p in pins]}），不猜哪条是当前的",
                  file=sys.stderr)
            return 2
    except urllib.error.HTTPError as e:
        print("POST-FAIL: http=%s %s" % (e.code, e.read().decode()[:300]), file=sys.stderr)
        return 1
    except (urllib.error.URLError, TimeoutError) as e:
        print("INCOMPLETE: 发不出去 %r" % (e,), file=sys.stderr)
        return 2
    print(json.dumps({"kind": "handoff_pin", "issue": post, "mode": mode,
                      "comment_id": got.get("id"), "html_url": got.get("html_url"),
                      "chars": len(body)}, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
